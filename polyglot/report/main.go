// Command report merges the Go results of ZeRechnung
// (bench_facturx.txt, survey_facturx.txt, produced by ecosystem/run.sh)
// with the results of the other languages (bench_<lang>.jsonl,
// survey_<lang>.jsonl: TypeScript, Python, Rust, Java, C#, C, C++, PHP) into
// Markdown comparison tables. It adds the allocations of one call when the
// alloc pass ran (alloc_<lang>.jsonl: TypeScript, Python, Rust; Go from the
// benchmarks), and the CPU time and peak memory tables when the resources
// pass ran (resources_<lang>.jsonl, Go included).
//
// Usage: go run . ../results/2026-11-17 > ../results/2026-11-17/tables.md
package main

import (
	"bufio"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strconv"
	"strings"
)

// result is one library on one benchmark.
type result struct {
	lib, lang, version string
	status             string  // ok, unsupported, fail
	ns                 float64 // median ns/op
	first              float64 // first call in the process, 0 if unknown
	note               string
}

type key struct{ lib, lang string }

// resource is one library on one benchmark in the resources pass: a process
// that ran that benchmark only.
type resource struct {
	status string
	ns     float64 // median wall ns/op of the pass
	cpu    float64 // median CPU ns/op over the same series
	rss    float64 // peak resident set size of the process, bytes
	child  bool    // the library runs child processes, not counted
}

// goLib is the name of ZeRechnung in the tables and in the records of
// run.sh; goOneCore is its second round of the resources pass, GOMAXPROCS=1.
const (
	goLib     = "ZeRechnung"
	goOneCore = "ZeRechnung, GOMAXPROCS=1"
)

type group struct {
	title   string
	benches []string
	labels  []string
	survey  string // survey column shown after the name ("validate" or "")
}

var groups = []group{
	{"Extraction", []string{"Extract_Small", "Extract_Large", "Extract_Minimum", "Extract_Extended"},
		[]string{"EN 16931, 149 KB", "EN 16931, 1.1 MB", "MINIMUM FNFE, 89 KB", "EXTENDED ZF 2.0, 157 KB"}, ""},
	{"Parsing XML → model", []string{"Parse_Small", "Parse_Lines", "Parse_Large"},
		[]string{"13 KB", "19 KB", "1.3 MB"}, ""},
	{"Parsing and validation", []string{"ParseValidate_Small", "ParseValidate_Lines", "ParseValidate_Large"},
		[]string{"13 KB", "19 KB", "1.3 MB"}, "validate"},
	{"Writing model → XML", []string{"Write_Small", "Write_Lines"},
		[]string{"13 KB", "19 KB"}, ""},
	{"Embedding into a PDF", []string{"EmbedClassic_Small", "Embed_Small"},
		[]string{"classic xref host", "xref-stream host"}, ""},
	{"Hybrid PDF check", []string{"CheckPDF_Small", "CheckPDF_Large"},
		[]string{"149 KB", "1.1 MB"}, ""},
}

var (
	goBench  = regexp.MustCompile(`^Benchmark(\S+?)-\d+\s+\d+\s+([\d.]+) ns/op`)
	goSurvey = regexp.MustCompile(`SURVEY (validate|extract|parse): (\d+)/(\d+)`)
	goVer    = regexp.MustCompile(`^go version (go\S+)`)
)

var langNames = map[string]string{
	"go": "Go", "typescript": "TypeScript", "python": "Python", "rust": "Rust",
	"java": "Java", "csharp": "C#", "c": "C", "cpp": "C++", "php": "PHP",
}

// langs is the order of the languages in every table.
var langs = []string{"go", "typescript", "python", "rust", "java", "csharp", "c", "cpp", "php"}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: report <results dir>")
		os.Exit(2)
	}
	dir := os.Args[1]
	res := map[string]map[key]result{} // bench -> lib -> result
	surveys := map[key]map[string]string{}
	notes := map[key]map[string][]string{} // lib -> note -> benches

	if err := loadGo(dir, res, surveys); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	files, _ := filepath.Glob(filepath.Join(dir, "bench_*.jsonl"))
	for _, f := range files {
		if err := loadJSONBench(f, res, notes); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	files, _ = filepath.Glob(filepath.Join(dir, "survey_*.jsonl"))
	for _, f := range files {
		if err := loadJSONSurvey(f, surveys); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}

	fmt.Printf("<!-- Generated by polyglot/report from %s -->\n", filepath.Base(dir))
	printSurveys(surveys)
	for _, g := range groups {
		printGroup(g, res, surveys)
	}
	printAllocs(loadAllocs(dir))

	rs := map[string]map[key]resource{}
	files, _ = filepath.Glob(filepath.Join(dir, "resources_*.jsonl"))
	for _, f := range files {
		if err := loadResources(f, rs); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	if len(rs) > 0 {
		printResourcesByLang(rs)
		for _, g := range groups {
			printResGroup(g, rs, "cpu")
		}
		for _, g := range groups {
			printResGroup(g, rs, "mem")
		}
	}
	printNotes(notes)
}

// alloc is what one call of one benchmark allocates.
type alloc struct {
	status string  // ok, unsupported, fail
	bytes  float64 // bytes allocated
	allocs float64 // number of allocations, -1 when the language does not count them
	lower  bool    // a garbage collection ran during the count: bytes is a lower bound
}

// allocColumns are the columns of the allocation table, as in the Go report.
var allocColumns = []struct{ bench, label string }{
	{"Extract_Small", "Extraction, 149 KB PDF"},
	{"Parse_Small", "Parsing, 13 KB XML"},
	{"ParseValidate_Small", "Validation, 13 KB XML"},
	{"ParseValidate_Large", "Validation, 1.3 MB XML"},
	{"Write_Small", "Writing, 13 KB XML"},
	{"Embed_Small", "Embedding, xref-stream host"},
	{"CheckPDF_Small", "Check, 149 KB PDF"},
}

var goMem = regexp.MustCompile(`^Benchmark(\S+?)-\d+\s+\d+\s+[\d.]+ ns/op(?:\s+[\d.]+ MB/s)?\s+(\d+) B/op\s+(\d+) allocs/op`)

// loadAllocs reads the allocations of ZeRechnung from bench_facturx.txt
// (go test -benchmem) and those of the other languages from alloc_<lang>.jsonl.
func loadAllocs(dir string) map[key]map[string]alloc {
	out := map[key]map[string]alloc{}
	put := func(k key, bench string, a alloc) {
		if out[k] == nil {
			out[k] = map[string]alloc{}
		}
		out[k][bench] = a
	}
	bytes, allocs := map[string][]float64{}, map[string][]float64{}
	eachLine(filepath.Join(dir, "bench_facturx.txt"), func(line string) {
		if m := goMem.FindStringSubmatch(line); m != nil {
			b, _ := strconv.ParseFloat(m[2], 64)
			n, _ := strconv.ParseFloat(m[3], 64)
			bytes[m[1]] = append(bytes[m[1]], b)
			allocs[m[1]] = append(allocs[m[1]], n)
		}
	})
	for b := range bytes {
		put(key{goLib, "go"}, b, alloc{"ok", median(bytes[b]), median(allocs[b]), false})
	}
	files, _ := filepath.Glob(filepath.Join(dir, "alloc_*.jsonl"))
	for _, f := range files {
		eachLine(f, func(line string) {
			var r struct {
				Lang, Lib, Bench, Status string
				Bytes                    float64
				Allocs                   *float64
				Gcs                      int
			}
			if strings.TrimSpace(line) == "" || json.Unmarshal([]byte(line), &r) != nil {
				return
			}
			a := alloc{status: r.Status, bytes: r.Bytes, allocs: -1, lower: r.Gcs > 0}
			if r.Allocs != nil {
				a.allocs = *r.Allocs
			}
			put(key{r.Lib, r.Lang}, r.Bench, a)
		})
	}
	return out
}

func printAllocs(m map[key]map[string]alloc) {
	best := map[string]float64{}
	var order []key
	for k, runs := range m {
		shown := false
		for _, c := range allocColumns {
			if r, ok := runs[c.bench]; ok && r.status == "ok" {
				shown = true
				if v, ok := best[c.bench]; !ok || r.bytes < v {
					best[c.bench] = r.bytes
				}
			}
		}
		if shown {
			order = append(order, k)
		}
	}
	if len(order) == 0 {
		return
	}
	sort.Slice(order, func(i, j int) bool { return less(order[i], order[j]) })
	fmt.Print("\n#### Allocations per call\n\n")
	head := []string{"Library", "Language"}
	for _, c := range allocColumns {
		head = append(head, c.label)
	}
	fmt.Println("| " + strings.Join(head, " | ") + " |")
	fmt.Println("|" + strings.Repeat("---|", len(head)))
	for _, k := range order {
		row := []string{name(k), langNames[k.lang]}
		for _, c := range allocColumns {
			r, ok := m[k][c.bench]
			switch {
			case !ok || r.status == "unsupported":
				row = append(row, "—")
			case r.status != "ok":
				row = append(row, "failed")
			default:
				v := fmtBytes(r.bytes)
				if r.lower {
					v = "≥ " + v
				}
				if r.allocs >= 0 {
					v += " · " + decimal(r.allocs, 0)
				}
				if r.bytes <= best[c.bench] {
					v = "**" + v + "**"
				}
				row = append(row, v)
			}
		}
		fmt.Println("| " + strings.Join(row, " | ") + " |")
	}
	fmt.Println("\nBytes allocated · number of allocations, for one call, after the same result check and a warm-up. Go: `go test -benchmem`, median of the runs. Rust: the harness's global allocator, which counts every `alloc` and `realloc`. Python: `PYTHONMALLOC=malloc` and a counter injected into the process, which counts every `malloc`, Python objects and C extensions included (libxml2, qpdf). TypeScript: growth of the V8 heap and of the ArrayBuffers during the series of calls; V8 does not count its allocations, hence no count, and \"≥\" when a garbage collection ran during the series. In bold: fewest bytes allocated in the column.")
}

// fmtBytes formats a size in KB and MB (powers of 1024), as on the wiki.
func fmtBytes(b float64) string {
	switch {
	case b >= 1000<<20:
		return decimal(b/(1<<30), 1) + " GB"
	case b >= 1000<<10:
		return decimal(b/(1<<20), 1) + " MB"
	case b >= 1<<10:
		return decimal(b/(1<<10), 0) + " KB"
	default:
		return decimal(b, 0) + " B"
	}
}

func loadGo(dir string, res map[string]map[key]result, surveys map[key]map[string]string) error {
	k := key{goLib, "go"}
	raw := map[string][]float64{}
	version := ""
	err := eachLine(filepath.Join(dir, "bench_facturx.txt"), func(line string) {
		if m := goVer.FindStringSubmatch(line); m != nil {
			version = m[1]
		}
		if m := goBench.FindStringSubmatch(line); m != nil {
			ns, _ := strconv.ParseFloat(m[2], 64)
			raw[m[1]] = append(raw[m[1]], ns)
		}
	})
	if err != nil {
		return err
	}
	for b, v := range raw {
		put(res, b, k, result{lib: k.lib, lang: "go", version: version, status: "ok", ns: median(v)})
	}
	eachLine(filepath.Join(dir, "survey_facturx.txt"), func(line string) {
		if m := goSurvey.FindStringSubmatch(line); m != nil {
			if surveys[k] == nil {
				surveys[k] = map[string]string{}
			}
			surveys[k][m[1]] = m[2] + "/" + m[3]
		}
	})
	return nil
}

func loadJSONBench(path string, res map[string]map[key]result, notes map[key]map[string][]string) error {
	return eachLine(path, func(line string) {
		var r struct {
			Lang, Lib, Version, Bench, Status, Note string
			NsPerOp                                 []float64 `json:"ns_per_op"`
			FirstCallNs                             float64   `json:"first_call_ns"`
		}
		if strings.TrimSpace(line) == "" || json.Unmarshal([]byte(line), &r) != nil {
			return
		}
		k := key{r.Lib, r.Lang}
		out := result{lib: r.Lib, lang: r.Lang, version: r.Version, status: r.Status, first: r.FirstCallNs, note: r.Note}
		if r.Status == "ok" && len(r.NsPerOp) > 0 {
			out.ns = median(r.NsPerOp)
		}
		put(res, r.Bench, k, out)
		// Notes of unsupported operations only say why; keep the others.
		if r.Note != "" && r.Status != "unsupported" {
			if notes[k] == nil {
				notes[k] = map[string][]string{}
			}
			notes[k][r.Note] = append(notes[k][r.Note], r.Bench)
		}
	})
}

func loadJSONSurvey(path string, surveys map[key]map[string]string) error {
	return eachLine(path, func(line string) {
		var r struct {
			Lang, Lib, Op string
			Ok, Total     int
		}
		if strings.TrimSpace(line) == "" || json.Unmarshal([]byte(line), &r) != nil {
			return
		}
		k := key{r.Lib, r.Lang}
		if surveys[k] == nil {
			surveys[k] = map[string]string{}
		}
		surveys[k][r.Op] = fmt.Sprintf("%d/%d", r.Ok, r.Total)
	})
}

func loadResources(path string, rs map[string]map[key]resource) error {
	return eachLine(path, func(line string) {
		var r struct {
			Lang, Lib, Bench, Status, Note string
			NsPerOp                        []float64 `json:"ns_per_op"`
			CPUNsPerOp                     []float64 `json:"cpu_ns_per_op"`
			MaxRSSBytes                    float64   `json:"max_rss_bytes"`
		}
		if strings.TrimSpace(line) == "" || json.Unmarshal([]byte(line), &r) != nil {
			return
		}
		out := resource{status: r.Status, rss: r.MaxRSSBytes, child: strings.Contains(r.Note, "child process")}
		if r.Status == "ok" && len(r.NsPerOp) > 0 && len(r.CPUNsPerOp) > 0 {
			out.ns, out.cpu = median(r.NsPerOp), median(r.CPUNsPerOp)
		} else if r.Status == "ok" {
			out.status = "fail"
		}
		k := key{r.Lib, r.Lang}
		if rs[r.Bench] == nil {
			rs[r.Bench] = map[key]resource{}
		}
		rs[r.Bench][k] = out
	})
}

func put(res map[string]map[key]result, bench string, k key, r result) {
	if res[bench] == nil {
		res[bench] = map[key]result{}
	}
	res[bench][k] = r
}

