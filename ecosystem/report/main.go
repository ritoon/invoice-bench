// Command report turns the raw outputs of run.sh (bench_*.txt, survey_*.txt
// and cases_*.jsonl) into the Markdown comparison tables used on the wiki.
//
// Usage: go run . ../results/2026-11-16 > ../results/2026-11-16/tables.md
