func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: report <results dir>")
		os.Exit(2)
	}
	dir := os.Args[1]
	results, err := loadBenches(dir) // bench -> lib -> run
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	surveys := loadSurveys(dir) // lib -> kind -> "n/total"

	fmt.Printf("<!-- Generated by ecosystem/report from %s -->\n", filepath.Base(dir))
	printSurveys(surveys)
	if err := printCases(dir, results); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	for _, g := range groups {
		printGroup(g, results, surveys)
	}
	printAllocs(results)
}

// allocColumns are the columns of the allocation table: one call of each
// operation, on the inputs of the site's charts.
var allocColumns = []struct{ bench, label string }{
	{"Extract_Small", "Extraction, 149 KB PDF"},
	{"Parse_Small", "Parsing, 13 KB XML"},
	{"ParseValidate_Small", "Validation, 13 KB XML"},
	{"ParseValidate_Large", "Validation, 1.3 MB XML"},
	{"Write_Small", "Writing, 13 KB XML"},
	{"Embed_Small", "Embedding, xref-stream host"},
	{"CheckPDF_Small", "Check, 149 KB PDF"},
}

// printAllocs prints, for each library, the bytes and the allocations of one
// call (go test -benchmem), ZeRechnung first, with the encoding/xml floor as a
// reference under the reading column.
func printAllocs(res map[string]map[string]run) {
	libs := map[string]bool{}
	best := map[string]float64{}
	for _, c := range allocColumns {
		for l, r := range res[c.bench] {
			libs[l] = true
			if v, ok := best[c.bench]; !ok || r.bytes < v {
				best[c.bench] = r.bytes
			}
		}
	}
	if len(libs) == 0 {
		return
	}
	order := keys(libs)
	sort.Slice(order, func(i, j int) bool {
		if (order[i] == "facturx") != (order[j] == "facturx") {
			return order[i] == "facturx"
		}
		return strings.ToLower(display(order[i])) < strings.ToLower(display(order[j]))
	})
	cell := func(r run) string { return fmtBytes(r.bytes) + " · " + thousands(r.allocs) }

	fmt.Print("\n#### Allocations per call\n\n")
	head := []string{"Library"}
	for _, c := range allocColumns {
		head = append(head, c.label)
	}
	fmt.Println("| " + strings.Join(head, " | ") + " |")
	fmt.Println("|" + strings.Repeat("---|", len(head)))
	for _, l := range order {
		row := []string{display(l)}
		for _, c := range allocColumns {
			r, ok := res[c.bench][l]
			switch {
			case !ok:
				row = append(row, "—")
			case r.bytes <= best[c.bench]:
				row = append(row, "**"+cell(r)+"**")
			default:
				row = append(row, cell(r))
			}
		}
		fmt.Println("| " + strings.Join(row, " | ") + " |")
	}
	if r, ok := res["Floor_XMLRawToken_Small"]["floor"]; ok {
		row := []string{"*floor: `encoding/xml` tokens*"}
		for _, c := range allocColumns {
			if c.bench == "Parse_Small" {
				row = append(row, "*"+cell(r)+"*")
			} else {
				row = append(row, "")
			}
		}
		fmt.Println("| " + strings.Join(row, " | ") + " |")
	}
	fmt.Println("\nBytes allocated · number of allocations, for one call (`go test -benchmem`, median of the runs). \"—\": operation not offered, or failed. In bold: fewest bytes allocated in the column.")
}

func loadBenches(dir string) (map[string]map[string]run, error) {
	files, err := filepath.Glob(filepath.Join(dir, "bench_*.txt"))
	if err != nil {
		return nil, err
	}
	raw := map[string]map[string][]run{}
	for _, f := range files {
		lib := strings.TrimSuffix(strings.TrimPrefix(filepath.Base(f), "bench_"), ".txt")
		err := eachLine(f, func(line string) {
			m := benchLine.FindStringSubmatch(line)
			if m == nil {
				return
			}
			ns, _ := strconv.ParseFloat(m[2], 64)
			by, _ := strconv.ParseFloat(m[3], 64)
			al, _ := strconv.ParseFloat(m[4], 64)
			if raw[m[1]] == nil {
				raw[m[1]] = map[string][]run{}
			}
			raw[m[1]][lib] = append(raw[m[1]][lib], run{ns, by, al})
		})
		if err != nil {
			return nil, err
		}
	}
	out := map[string]map[string]run{}
	for b, libs := range raw {
		out[b] = map[string]run{}
		for l, rs := range libs {
			out[b][l] = run{
				median(rs, func(r run) float64 { return r.ns }),
				median(rs, func(r run) float64 { return r.bytes }),
				median(rs, func(r run) float64 { return r.allocs }),
			}
		}
	}
	return out, nil
}

func loadSurveys(dir string) map[string]map[string]string {
	out := map[string]map[string]string{}
	files, _ := filepath.Glob(filepath.Join(dir, "survey_*.txt"))
	for _, f := range files {
		lib := strings.TrimSuffix(strings.TrimPrefix(filepath.Base(f), "survey_"), ".txt")
		eachLine(f, func(line string) {
			if m := surveyLine.FindStringSubmatch(line); m != nil {
				if out[lib] == nil {
					out[lib] = map[string]string{}
				}
				out[lib][m[1]] = m[2] + "/" + m[3]
			}
		})
	}
	return out
}

func printSurveys(s map[string]map[string]string) {
	fmt.Print("\n#### Accuracy on the corpus\n\n")
	fmt.Println("| Library | Valid XML rejected | XML parsed | PDF extracted |")
	fmt.Println("|---|---|---|---|")
	libs := keys(s)
	sort.Slice(libs, func(i, j int) bool { return display(libs[i]) < display(libs[j]) })
	for _, l := range libs {
		fmt.Printf("| %s | %s | %s | %s |\n", display(l), orDash(s[l]["validate"]), orDash(s[l]["parse"]), orDash(s[l]["extract"]))
	}
}

// opFamilies are the operations of the Operations column of the confidence
// tables, by benchmark prefix (validation is what the cases measure).
var opFamilies = []struct{ prefix, name string }{
	{"Extract_", "extract"}, {"Parse_", "parse"}, {"Write_", "write"}, {"Embed", "embed"}, {"CheckPDF_", "check PDF"},
}

// printCases writes the confidence tables from the cases_*.jsonl files of
// dir (./run.sh cases), with the operations each library performed in the
// bench pass of dir.
func printCases(dir string, res map[string]map[string]run) error {
	all, err := cases.LoadRuns(dir)
	if err != nil {
		return err
	}
	var runs []cases.Run // the Go modules only
	for _, r := range all {
		if r.Lang == "go" {
			runs = append(runs, r)
		}
	}
	if len(runs) == 0 {
		return nil
	}
	cdir := os.Getenv("CASES_DIR")
	if cdir == "" {
		cdir = filepath.Join("..", "..", "cases")
	}
	idx, err := cases.LoadIndex(cdir)
	if err != nil {
		return err
	}
	libs, validates := map[string]bool{}, map[string]bool{}
	for b, m := range res {
		for l := range m {
			libs[l] = true
			validates[l] = validates[l] || strings.HasPrefix(b, "ParseValidate_")
		}
	}
	ops := map[string][]string{}
	for l := range libs {
		var list []string
		for _, f := range opFamilies {
			for b, m := range res {
				if _, ok := m[l]; ok && strings.HasPrefix(b, f.prefix) && !strings.HasPrefix(b, "ParseValidate_") {
					list = append(list, f.name)
					break
				}
			}
		}
		ops["go/"+l] = list
	}
	rated := map[string]bool{}
	for _, r := range runs {
		rated[r.Lib] = true
	}
	var unrated []string
	for l := range libs {
		if l != "floor" && !validates[l] && !rated[l] {
			unrated = append(unrated, display(l))
		}
	}
	sort.Strings(unrated)
	cases.Markdown(os.Stdout, idx, runs, cases.Options{
		Name:      func(_, lib string) string { return display(lib) },
		Ops:       ops,
		OpsSource: "the bench pass of the same campaign",
		Unrated:   unrated,
		Link:      "../../../cases/README.md",
	})
	return nil
}

func printGroup(g group, res map[string]map[string]run, surveys map[string]map[string]string) {
	libs := map[string]bool{}
	best := map[string]float64{}
	for _, b := range g.benches {
		for l, r := range res[b] {
			libs[l] = true
			if v, ok := best[b]; !ok || r.ns < v {
				best[b] = r.ns
			}
		}
	}
	if len(libs) == 0 {
		return
	}
	first := g.benches[0]
	order := keys(libs)
	sort.Slice(order, func(i, j int) bool {
		a, aok := res[first][order[i]]
		b, bok := res[first][order[j]]
		switch {
		case aok && bok:
			return a.ns < b.ns
		case aok != bok:
			return aok
		default:
			return display(order[i]) < display(order[j])
		}
	})

	fmt.Printf("\n#### %s\n\n", g.title)
	head := []string{"Library"}
	if g.extra != "" {
		head = append(head, "Valid rejected /26")
	}
	head = append(head, g.labels...)
	head = append(head, "Memory/op", "Allocations/op")
	fmt.Println("| " + strings.Join(head, " | ") + " |")
	fmt.Println("|" + strings.Repeat("---|", len(head)))
	for _, l := range order {
		row := []string{display(l)}
		if g.extra != "" {
			row = append(row, orDash(surveys[l][g.extra]))
		}
		for _, b := range g.benches {
			r, ok := res[b][l]
			switch {
			case !ok:
				row = append(row, g.missing)
			case r.ns <= best[b]*1.0001:
				row = append(row, "**"+fmtNs(r.ns)+"**")
			default:
				row = append(row, fmt.Sprintf("%s (×%s)", fmtNs(r.ns), decimal(r.ns/best[b], 1)))
			}
		}
		if r, ok := res[first][l]; ok {
			row = append(row, fmtBytes(r.bytes), thousands(r.allocs))
		} else {
			row = append(row, "—", "—")
		}
		fmt.Println("| " + strings.Join(row, " | ") + " |")
	}
	fmt.Printf("\nMemory and allocations: column \"%s\". Sorted on that same column.\n", g.labels[0])
}

func eachLine(path string, fn func(string)) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 64*1024), 1024*1024)
	for sc.Scan() {
		fn(sc.Text())
	}
	return sc.Err()
}

func median(rs []run, f func(run) float64) float64 {
	v := make([]float64, len(rs))
	for i, r := range rs {
		v[i] = f(r)
	}
	slices.Sort(v)
	n := len(v)
	if n%2 == 1 {
		return v[n/2]
	}
	return (v[n/2-1] + v[n/2]) / 2
}

func fmtNs(ns float64) string {
	switch {
	case ns >= 1e6:
		return decimal(ns/1e6, 2) + " ms"
	case ns >= 1e5:
		return decimal(ns/1e3, 0) + " µs"
	case ns >= 1e3:
		return decimal(ns/1e3, 1) + " µs"
	default:
		return decimal(ns, 0) + " ns"
	}
}

func fmtBytes(b float64) string {
	switch {
	case b >= 1000<<20:
		return decimal(b/(1<<30), 1) + " GB"
	case b >= 1000<<10:
		return decimal(b/(1<<20), 1) + " MB"
	case b >= 1<<10:
		return decimal(b/(1<<10), 0) + " KB"
	default:
		return decimal(b, 0) + " B"
	}
}

// decimal formats v with prec decimals and a decimal point.
func decimal(v float64, prec int) string {
	return strconv.FormatFloat(v, 'f', prec, 64)
}

// thousands groups digits with a comma.
func thousands(v float64) string {
	s := strconv.FormatInt(int64(math.Round(v)), 10)
	var b strings.Builder
	for i, c := range s {
		if i > 0 && (len(s)-i)%3 == 0 {
			b.WriteByte(',')
		}
		b.WriteRune(c)
	}
	return b.String()
}

func display(lib string) string {
	if n, ok := names[lib]; ok {
		return n
	}
	return lib
}

func orDash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}

func keys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	return out
}
